import { readFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { stringify } from "yaml";
import type {
  Diagnostic,
  JsonObject,
  RenderedFile,
  ResolvedContext,
  Skill,
} from "../../core/types.js";
import { readTree } from "../../model/files.js";
import { externalOrigin, skillDirectory } from "../../model/external.js";
import { convertText } from "./conversion.js";

export function file(relPath: string, content: string | Buffer, mode = 0o644): RenderedFile {
  return { kind: "file", relPath, content, mode };
}

function provenance(ctx: ResolvedContext, path: string): string {
  return relative(ctx.model.repoDir, path).split("\\").join("/").replaceAll("--", "&#45;&#45;");
}

export async function renderSkills(ctx: ResolvedContext, diagnostics: Diagnostic[]) {
  const files: RenderedFile[] = [];
  for (const skill of ctx.model.harnesses.omo?.skills ?? []) {
    const supportFiles = await Promise.all(
      skill.supportFiles.map(async (support) => ({
        ...support,
        bytes: await readFile(support.sourcePath),
      })),
    );
    const options = {
      file: skill.file,
      skillDir: skillDirectory(skill, ctx.model.repoDir),
    };
    const body = convertText(skill.body, ctx, options);
    diagnostics.push(...body.diagnostics);
    const frontmatter = skill.frontmatter;
    const header = {
      name: frontmatter.name,
      description: frontmatter.description,
      ...(frontmatter.license === undefined ? {} : { license: frontmatter.license }),
      ...(frontmatter.compatibility === undefined
        ? {}
        : { compatibility: frontmatter.compatibility }),
      ...(frontmatter["disable-model-invocation"] === true
        ? { "disable-model-invocation": true }
        : {}),
    };
    files.push(
      file(
        `skills/${skill.name}/SKILL.md`,
        `---\n${stringify(header, { defaultStringType: "QUOTE_DOUBLE" })}---\n\n<!-- Generated by skillerie. Source: ${(externalOrigin(skill) ? `${externalOrigin(skill)}/SKILL.md` : provenance(ctx, skill.file)).replaceAll("--", "&#45;&#45;")} -->\n\n${skillGuidance(skill, [skill.body, ...supportFiles.filter((entry) => /\.md$/i.test(entry.relPath)).map((entry) => entry.bytes.toString("utf8"))].join("\n"))}\n\n${body.text.trim()}\n`,
      ),
    );
    for (const support of supportFiles) {
      const bytes = support.bytes;
      const converted = /\.md$/i.test(support.relPath)
        ? convertText(bytes.toString("utf8"), ctx, { ...options, file: support.sourcePath })
        : { text: bytes, diagnostics: [] };
      diagnostics.push(...converted.diagnostics);
      files.push(file(`skills/${skill.name}/${support.relPath}`, converted.text, support.mode));
    }
  }
  // RenderedFile has no directory entry; retain an empty exclusive skills root.
  if (files.length === 0) files.push(file("skills/.keep", ""));
  return files;
}

function skillGuidance(skill: Skill, sourceText: string): string {
  return [
    skill.external
      ? "Resolve skill-relative paths from this installed skill's directory."
      : `Source directory: \`${dirname(skill.file)}\`. Resolve skill-relative paths from this directory.`,
    "Work on the invocation's working repository, not the skill source repository.",
    "Use the invocation arguments as context; read referenced SKILL.md files and follow their instructions.",
    ...(skill.frontmatter["disable-model-invocation"] === true
      ? ["Run this skill only when explicitly invoked."]
      : []),
    ...(/\bmcp__[\w-]+__[\w-]+/.test(sourceText)
      ? [
          "MCP tools may need discovery before use. Use MCP tool discovery to find the named server and tool, then call the discovered tool.",
        ]
      : []),
  ].join("\n");
}

export function renderAgents(ctx: ResolvedContext, diagnostics: Diagnostic[]): JsonObject {
  const entries: [string, JsonObject][] = [];
  for (const agent of ctx.model.harnesses.omo?.agents ?? []) {
    const { frontmatter } = agent;
    for (const [field, requested] of [
      ["readOnly", frontmatter.readOnly === true],
      ["noShell", frontmatter.noShell === true],
    ] as const) {
      if (requested) {
        diagnostics.push({
          severity: "error",
          code: "omo.permission",
          message: `OMO cannot enforce ${field} for agent ${agent.name}.`,
          file: agent.file,
          jsonPath: `/frontmatter/${field}`,
        });
      }
    }
    const converted = convertText(agent.body, ctx, { file: agent.file, childAgent: true });
    diagnostics.push(...converted.diagnostics);
    const preload = frontmatter.skills ?? [];
    const notes = [
      "Inherit the parent model unless runtime configuration selects another model.",
      "Use the harness memory facilities for durable findings.",
      "Pass questions to the parent when user input is needed.",
      ...(preload.length
        ? [
            `Read and follow these skills before starting: ${preload.map((name) => `\`/` + name + "`").join(", ")}.`,
          ]
        : []),
    ];
    const maxTurns = frontmatter.maxTurns;
    if (maxTurns !== undefined && (!Number.isInteger(maxTurns) || maxTurns <= 0)) {
      diagnostics.push({
        severity: "error",
        code: "omo.maxTurns",
        message: `Agent ${agent.name} requires a positive integer maxTurns.`,
        file: agent.file,
      });
    }
    entries.push([
      agent.name,
      {
        description: frontmatter.description,
        prompt: [...notes, "", converted.text.trim()].join("\n"),
        ...(maxTurns === undefined ? {} : { max_turns: maxTurns }),
      },
    ]);
  }
  return Object.fromEntries(entries.sort(([left], [right]) => (left < right ? -1 : 1)));
}

export function renderInstructions(ctx: ResolvedContext, diagnostics: Diagnostic[]): string {
  const sections = ["<!-- Generated by skillerie. Edit the source instructions and rules. -->"];
  const instructions = ctx.model.instructions;
  if (instructions !== undefined && !opencodeProvidesInstructions(ctx)) {
    const converted = convertText(instructions.body, ctx, { file: instructions.file });
    diagnostics.push(...converted.diagnostics);
    sections.push(`<!-- Source: ${provenance(ctx, instructions.file)} -->`, converted.text.trim());
  }
  for (const rule of [...(ctx.model.harnesses.omo?.rules ?? [])].sort((a, b) =>
    a.name < b.name ? -1 : a.name > b.name ? 1 : 0,
  )) {
    const converted = convertText(rule.body, ctx, { file: rule.file });
    diagnostics.push(...converted.diagnostics);
    sections.push(
      `<!-- Rule: ${provenance(ctx, rule.file)} -->`,
      (rule.paths.length ? `---\n${stringify({ paths: rule.paths })}---\n\n` : "") +
        converted.text.trim(),
    );
  }
  return sections.join("\n\n") + "\n";
}

/**
 * OMO always loads ~/.config/opencode/AGENTS.md as a user rule, so when the
 * opencode harness installs instructions there, repeating them here only
 * duplicates them in OMO's prompt.
 */
function opencodeProvidesInstructions(ctx: ResolvedContext): boolean {
  const opencode = ctx.snapshot.config.harnesses.opencode;
  return (
    opencode?.enabled === true &&
    opencode.path === join(ctx.snapshot.config.paths.home, ".config", "opencode")
  );
}

export async function renderPayloads(ctx: ResolvedContext, diagnostics: Diagnostic[]) {
  const files: RenderedFile[] = [];
  for (const seed of ctx.model.seeds.filter((entry) => entry.harness === "omo")) {
    files.push(file(`seeds/${seed.relPath}`, await readFile(seed.sourcePath), seed.mode));
  }
  for (const asset of ctx.model.harnesses.omo?.assets ?? []) {
    switch (asset.kind) {
      case "file": {
        const entries = await readTree(asset.sourcePath, diagnostics);
        const entry = entries[0];
        if (entry !== undefined)
          files.push(file(`assets/${asset.relPath}`, entry.content, entry.mode));
        break;
      }
      case "directory":
        for (const entry of await readTree(asset.sourcePath, diagnostics)) {
          files.push(file(join("assets", asset.relPath, entry.relPath), entry.content, entry.mode));
        }
        break;
      default:
        unreachable(asset.kind);
    }
  }
  return files;
}

function unreachable(value: never): never {
  throw new TypeError(`Unknown asset kind: ${String(value)}`);
}
