import { parse, printParseErrorCode } from "jsonc-parser";
import type { ParseError } from "jsonc-parser";
import type { Diagnostic, JsonObject, ResolvedContext } from "../../core/types.js";
import { resolveMcpServers } from "../../model/index.js";
import { isJsonObject } from "../../model/json.js";

export const notice = "// Generated by skillerie. Edit the source configuration instead.\n";

export function templateObject(
  ctx: ResolvedContext,
  relPath: string,
  diagnostics: Diagnostic[],
): JsonObject {
  const template = ctx.model.templates.omo?.files.find((entry) => entry.relPath === relPath);
  if (template === undefined) return {};
  const errors: ParseError[] = [];
  const value: unknown = parse(template.content, errors, {
    allowTrailingComma: template.format === "jsonc",
    disallowComments: template.format !== "jsonc",
  });
  for (const error of errors) {
    diagnostics.push({
      severity: "error",
      code: "omo.template",
      message: printParseErrorCode(error.error),
      file: template.file,
      line: template.content.slice(0, error.offset).split("\n").length,
    });
  }
  if (isJsonObject(value)) return value;
  diagnostics.push({
    severity: "error",
    code: "omo.template",
    message: "Expected a configuration object.",
    file: template.file,
  });
  return {};
}

export function renderConfig(
  ctx: ResolvedContext,
  agents: JsonObject,
  diagnostics: Diagnostic[],
): string {
  const template = templateObject(ctx, "omo.jsonc", diagnostics);
  const section = template["[native]"];
  if (section !== undefined && !isJsonObject(section)) {
    diagnostics.push({
      severity: "error",
      code: "omo.template",
      message: "The [native] section must be an object.",
      jsonPath: "/[native]",
    });
  }
  const native = isJsonObject(section) ? section : {};
  const overrides = native["agents"];
  if (overrides !== undefined && !isJsonObject(overrides)) {
    diagnostics.push({
      severity: "error",
      code: "omo.template",
      message: "Native agents must be an object.",
      jsonPath: "/[native]/agents",
    });
  }
  const entries = isJsonObject(overrides) ? overrides : {};
  const merged: Record<string, JsonObject> = {};
  for (const name of [...new Set([...Object.keys(agents), ...Object.keys(entries)])].sort()) {
    const generated = agents[name];
    const override = entries[name];
    if (override !== undefined && !isJsonObject(override)) {
      diagnostics.push({
        severity: "error",
        code: "omo.agentOverride",
        message: `Override for agent ${name} must be an object.`,
      });
      continue;
    }
    if (
      generated !== undefined &&
      override !== undefined &&
      (Object.hasOwn(override, "description") || Object.hasOwn(override, "prompt"))
    ) {
      diagnostics.push({
        severity: "error",
        code: "omo.agentClash",
        message: `Template prompt or description clashes with generated agent ${name}.`,
      });
    }
    Object.defineProperty(merged, name, {
      value: { ...(isJsonObject(generated) ? generated : {}), ...override },
      enumerable: true,
    });
  }
  return (
    notice +
    JSON.stringify({ ...template, "[native]": { ...native, agents: merged } }, null, 2) +
    "\n"
  );
}

export function renderMcp(ctx: ResolvedContext, diagnostics: Diagnostic[]): string {
  const template = templateObject(ctx, "mcp.json", diagnostics);
  const mcp = ctx.model.mcp;
  const resolved = mcp === undefined ? {} : resolveMcpServers(mcp, "omo");
  const mcpServers: JsonObject = Object.fromEntries(
    Object.entries(resolved)
      .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
      .map(([name, server]) => {
        if (!(server.command?.trim() || server.url?.trim())) {
          diagnostics.push({
            severity: "error",
            code: "omo.mcp",
            message: `MCP server ${name} requires a command or URL.`,
            ...(mcp === undefined ? {} : { file: mcp.file }),
            jsonPath: `/mcpServers/${name.replaceAll("~", "~0").replaceAll("/", "~1")}`,
          });
        }
        const home = ctx.snapshot.config.paths.home;
        const expand = (value: string) => (value.startsWith("~/") ? home + value.slice(1) : value);
        return [
          name,
          {
            ...server,
            ...(server.command === undefined ? {} : { command: expand(server.command) }),
            ...(server.args === undefined ? {} : { args: server.args.map(expand) }),
          },
        ];
      }),
  );
  return JSON.stringify({ ...template, ...mcp?.settings, mcpServers }, null, 2) + "\n";
}
