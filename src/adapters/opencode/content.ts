import { readFile } from "node:fs/promises";
import { stringify } from "yaml";
import type { Agent, Diagnostic, JsonObject, RenderedFile, Skill } from "../../core/types.js";
import { capDescription } from "../../model/schema.js";
import { externalOrigin, skillDirectory } from "../../model/external.js";
import { capabilities, permissionNames } from "./capabilities.js";
import { convertText } from "./text.js";

export const generatedNotice = "<!-- Generated by skillerie. Edit the source repository. -->";

export function markdown(frontmatter: JsonObject, body: string): string {
  return `---\n${stringify(frontmatter).trimEnd()}\n---\n\n${body.trim()}\n`;
}

export function file(relPath: string, content: string | Buffer, mode = 0o644): RenderedFile {
  return { kind: "file", relPath, content, mode };
}

export async function renderSkill(
  skill: Skill,
  repoDir: string,
): Promise<{
  readonly files: readonly RenderedFile[];
  readonly diagnostics: readonly Diagnostic[];
}> {
  const skillDir = skillDirectory(skill, repoDir);
  const source = { file: skill.file, skillDir };
  const converted = convertText(skill.body, source);
  const diagnostics: Diagnostic[] = [...converted.diagnostics];
  const fields = skill.frontmatter;
  const frontmatter: JsonObject = {
    name: fields.name,
    description: capDescription(fields.description),
    ...(fields.license === undefined ? {} : { license: fields.license }),
    ...(fields.compatibility === undefined ? {} : { compatibility: fields.compatibility }),
  };
  const guidance = [
    generatedNotice,
    ...(skill.external
      ? [`<!-- Source: ${externalOrigin(skill)?.replaceAll("--", "&#45;&#45;")}/SKILL.md -->`]
      : []),
    "Resolve support paths from the base directory returned by the skill tool. Run project commands from the working repository, not the installed skill directory.",
    "Treat $ARGUMENTS as the invocation context supplied by the caller. If none was supplied, use the current request.",
    ...(fields["disable-model-invocation"]
      ? ["Use this skill only after an explicit user invocation; do not select it automatically."]
      : []),
    ...(/\b(?:task|background)\b/i.test(skill.body)
      ? [
          "Use only task features exposed by the runtime. Child agents inherit the current model unless the runtime selects another.",
        ]
      : []),
  ].join("\n\n");
  const files: RenderedFile[] = [
    file(
      `skills/${skill.name}/SKILL.md`,
      markdown(frontmatter, `${guidance}\n\n${converted.text}`),
    ),
  ];
  for (const support of skill.supportFiles) {
    const bytes = await readFile(support.sourcePath);
    let content: string | Buffer = bytes;
    if (support.relPath.endsWith(".md")) {
      const result = convertText(bytes.toString("utf8"), { ...source, file: support.sourcePath });
      diagnostics.push(...result.diagnostics);
      content = result.text;
    }
    files.push(file(`skills/${skill.name}/${support.relPath}`, content, support.mode));
  }
  if (fields["user-invocable"] !== false)
    files.push(
      file(
        `commands/${skill.name}.md`,
        markdown(
          { description: frontmatter["description"] ?? "" },
          `${generatedNotice}\n\nLoad skill(${JSON.stringify({ name: skill.name })}) and follow its instructions.\n\nInvocation context: $ARGUMENTS`,
        ),
      ),
    );
  return { files, diagnostics };
}

/** Omitted builtins are denied, but allowed entries keep their runtime policy. */
export function agentPermissions(agent: Agent): {
  readonly permission: JsonObject;
  readonly diagnostics: readonly Diagnostic[];
} {
  const restriction = agent.frontmatter.allowed_tools;
  const diagnostics: Diagnostic[] = [];
  const permission: Record<string, "deny"> = {};
  if (restriction !== undefined) {
    const names = typeof restriction === "string" ? restriction.split(",") : restriction;
    const allowed = new Set<string>();
    for (const entry of names) {
      const name = entry.trim();
      const native = Object.hasOwn(capabilities.toolMap, name)
        ? capabilities.toolMap[name]
        : permissionNames.find((item) => item === name);
      if (/^mcp__[\w-]+__[\w-]+$/.test(name)) continue;
      if (native === undefined) {
        diagnostics.push({
          severity: "error",
          code: "opencode.tool",
          message: `Unknown agent tool: ${name}.`,
          file: agent.file,
          jsonPath: "/frontmatter/allowed_tools",
        });
        continue;
      }
      allowed.add(native === "write" ? "edit" : native);
    }
    if (agent.frontmatter.skills?.length) allowed.add("skill");
    for (const name of permissionNames) if (!allowed.has(name)) permission[name] = "deny";
  }
  if (agent.frontmatter.noShell) {
    permission["bash"] = "deny";
    // A child with broader privileges could otherwise run shell on behalf of this agent.
    permission["task"] = "deny";
  }
  return { permission, diagnostics };
}

export function renderAgent(agent: Agent) {
  const converted = convertText(agent.body, { file: agent.file, childAgent: true });
  const permissions = agentPermissions(agent);
  const diagnostics: Diagnostic[] = [...converted.diagnostics, ...permissions.diagnostics];
  for (const [field, requested] of [
    ["allowed_tools", agent.frontmatter.allowed_tools !== undefined],
    ["readOnly", agent.frontmatter.readOnly === true],
  ] as const) {
    if (requested) {
      const allowlist = field === "allowed_tools";
      diagnostics.push({
        severity: allowlist ? "warn" : "error",
        code: allowlist ? "opencode.permission.unenforced" : "opencode.permission",
        message: allowlist
          ? `OpenCode cannot enforce allowed_tools for arbitrary tools; it is guidance only for ${agent.name}.`
          : `OpenCode deny-only permissions cannot enforce ${field} for arbitrary tools.`,
        file: agent.file,
        jsonPath: `/frontmatter/${field}`,
      });
    }
  }
  const skills = agent.frontmatter.skills ?? [];
  const guidance = [
    generatedNotice,
    "Inherit the runtime model; this agent does not select a model.",
    ...(skills.length
      ? [
          `Before starting, load ${skills.map((name) => `skill(${JSON.stringify({ name })})`).join(", ")}.`,
        ]
      : []),
    ...(/\bAskUserQuestion\b/.test(agent.body)
      ? [
          "If the child runtime does not expose question, return the question to the parent for delivery, then continue with its answer.",
        ]
      : []),
  ];
  return {
    file: file(
      `agents/${agent.name}.md`,
      markdown(
        {
          description: capDescription(agent.frontmatter.description),
          mode: "subagent",
          ...(agent.frontmatter.maxTurns === undefined
            ? {}
            : { steps: agent.frontmatter.maxTurns }),
          ...(Object.keys(permissions.permission).length
            ? { permission: permissions.permission }
            : {}),
        },
        [...guidance, converted.text].join("\n\n"),
      ),
    ),
    diagnostics,
  };
}
