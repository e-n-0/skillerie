import { join } from "node:path";
import type { Diagnostic, RenderedFile, RenderResult, ResolvedContext } from "../../core/types.js";
import { readTree } from "../../model/files.js";
import { renderConfig } from "./config.js";
import { file, markdown, renderAgent, renderSkill } from "./content.js";
import { convertText } from "./text.js";

export async function render(ctx: ResolvedContext): Promise<RenderResult> {
  const files: RenderedFile[] = [];
  const diagnostics: Diagnostic[] = [];
  const config = renderConfig(ctx);
  diagnostics.push(...config.diagnostics);
  if (config.config)
    files.push(
      file(
        "opencode.jsonc",
        `// Generated by skillerie. Edit the source repository.\n${JSON.stringify(config.config, null, 2)}\n`,
      ),
    );
  const sources = ctx.model.harnesses.opencode;
  for (const skill of sources?.skills ?? []) {
    const result = await renderSkill(skill, ctx.model.repoDir);
    files.push(...result.files);
    diagnostics.push(...result.diagnostics);
  }
  for (const agent of sources?.agents ?? []) {
    const result = renderAgent(agent);
    files.push(result.file);
    diagnostics.push(...result.diagnostics);
  }
  if (ctx.model.instructions) {
    const result = convertText(ctx.model.instructions.body, { file: ctx.model.instructions.file });
    diagnostics.push(...result.diagnostics);
    files.push(file("AGENTS.md", result.text));
  }
  for (const rule of sources?.rules ?? []) {
    const result = convertText(rule.body, { file: rule.file });
    diagnostics.push(...result.diagnostics);
    files.push(
      file(
        `rules/${rule.name}.md`,
        rule.paths.length ? markdown({ paths: rule.paths }, result.text) : result.text,
      ),
    );
  }
  for (const template of ctx.model.templates.opencode?.files ?? [])
    if (template.relPath !== "opencode.jsonc") files.push(file(template.relPath, template.content));
  for (const asset of sources?.assets ?? []) {
    const entries = await readTree(asset.sourcePath, diagnostics);
    for (const entry of entries)
      files.push(
        file(
          asset.kind === "file"
            ? asset.relPath
            : join(asset.relPath, entry.relPath).replaceAll("\\", "/"),
          entry.content,
          entry.mode,
        ),
      );
  }
  const seen = new Set<string>();
  for (const entry of files) {
    if (seen.has(entry.relPath))
      diagnostics.push({
        severity: "error",
        code: "opencode.outputCollision",
        message: `Multiple sources render ${entry.relPath}.`,
      });
    seen.add(entry.relPath);
  }
  return {
    files: files.sort((a, b) => (a.relPath < b.relPath ? -1 : a.relPath > b.relPath ? 1 : 0)),
    diagnostics,
    metadata: { adapter: "opencode", files: files.length },
  };
}
