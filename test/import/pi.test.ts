import { afterEach, beforeEach, expect, it } from "vitest";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import type { Environment } from "../../src/core/types.js";
import { parseFrontmatter } from "../../src/model/frontmatter.js";
import { hashJson, hashText } from "../../src/import/shared.js";
import { scanPi } from "../../src/import/pi.js";
import type { FoundAgent, FoundMcp, ScanContext } from "../../src/import/types.js";

let root: string;
let home: string;

beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), "skillerie-pi-import-"));
  home = join(root, "home");
  await mkdir(home, { recursive: true });
});

afterEach(async () => {
  await rm(root, { recursive: true, force: true });
});

async function put(relativePath: string, content: string): Promise<string> {
  const path = join(home, relativePath);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
  return path;
}

function context(managed: ScanContext["managed"] = () => false): ScanContext {
  const env: Environment = { HOME: home, PATH: "" };
  return { env, managed };
}

it("imports Pi agents, instructions, and MCP servers", async () => {
  // Given: a Pi home with authored files, an agent extension field, and MCP settings.
  const agentPath = await put(
    "agents/scout.md",
    "---\nname: scout\ndescription: Use when scouting a codebase.\ntools: read, grep\nmodel: pi\n---\nScout first.\n",
  );
  await put(
    "agents/general-purpose.md",
    "---\nname: general-purpose\ndescription: Generated by skillerie.\n---\n",
  );
  const instructions = "Use the repository's verification commands.\n";
  const instructionsPath = await put("AGENTS.md", instructions);
  const mcpPath = await put(
    "mcp.json",
    `{
  // Pi-only settings are not part of an imported server.
  "mcpServers": {
    "docs": {
      "url": "https://docs.example.com/mcp",
      "headers": {
        "Authorization": "Bearer sk-live-0123456789abcdef",
        "X-Team": "core"
      }
    }
  },
  "settings": { "theme": "dark" }
}
`,
  );

  // When: Pi's home is scanned.
  const result = await scanPi(home, context());

  // Then: authored content is inventoried, generated content is skipped, and secrets are scrubbed.
  expect(result.diagnostics).toEqual([]);
  expect(result.items.map((item) => `${item.kind}:${item.name}`).sort()).toEqual([
    "agent:scout",
    "instructions:instructions",
    "mcp:docs",
  ]);
  const agent = result.items.find((item): item is FoundAgent => item.kind === "agent");
  const expectedAgent = parseFrontmatter(
    "---\nname: scout\ndescription: Use when scouting a codebase.\n---\nScout first.\n",
    agentPath,
  );
  expect(agent?.path).toBe(agentPath);
  expect(agent?.dropped).toEqual(["model", "tools"]);
  expect(agent?.hash).toBe(
    expectedAgent.frontmatter
      ? hashText(
          `---\nname: scout\ndescription: Use when scouting a codebase.\n---\n${expectedAgent.body.trimEnd()}\n`,
        )
      : undefined,
  );
  const normalizedAgent = parseFrontmatter(agent?.markdown ?? "", agentPath);
  expect(Object.keys(normalizedAgent.frontmatter ?? {}).sort()).toEqual(["description", "name"]);

  expect(result.items).toContainEqual(
    expect.objectContaining({
      kind: "instructions",
      name: "instructions",
      path: instructionsPath,
      hash: hashText(instructions),
    }),
  );
  const mcp = result.items.find((item): item is FoundMcp => item.kind === "mcp");
  const expectedServer = {
    url: "https://docs.example.com/mcp",
    headers: { "X-Team": "core" },
  };
  expect(mcp).toMatchObject({
    name: "docs",
    path: mcpPath,
    server: expectedServer,
    secrets: ["headers.Authorization"],
    hash: hashJson(expectedServer),
  });
});

it("skips managed agent, instructions, and MCP paths", async () => {
  // Given: each supported Pi path exists and the context marks all three as managed.
  const agentPath = await put(
    "agents/scout.md",
    "---\nname: scout\ndescription: Use when scouting.\n---\n",
  );
  const instructionsPath = await put("AGENTS.md", "managed instructions\n");
  const mcpPath = await put(
    "mcp.json",
    '{"mcpServers":{"docs":{"url":"https://docs.example.com"}}}',
  );

  // When: those paths are reported as managed.
  const result = await scanPi(
    home,
    context((path) => [agentPath, instructionsPath, mcpPath].includes(path)),
  );

  // Then: no managed item is imported.
  expect(result.items).toEqual([]);
  expect(result.diagnostics).toEqual([]);
});

it("returns a diagnostic for invalid MCP JSONC", async () => {
  // Given: an MCP file with an incomplete server value.
  const path = await put("mcp.json", '{\n  "mcpServers": { "docs": }\n}\n');

  // When: Pi's home is scanned.
  const result = await scanPi(home, context());

  // Then: invalid content is reported without throwing or creating an MCP item.
  expect(result.items).toEqual([]);
  expect(result.diagnostics).toContainEqual(
    expect.objectContaining({
      severity: "error",
      code: "pi.import.mcp",
      file: path,
      line: 2,
    }),
  );
});
